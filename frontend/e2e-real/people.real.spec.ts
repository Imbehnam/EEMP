import { expect, test } from '@playwright/test';

import { ADMIN, alertBox, api, apiLogin, PASSWORDS, signInBranchManager, signInDemoAdmin, textbox, unique } from './helpers';

test.describe.configure({ mode: 'serial' });

interface Paged<T> { items: T[] }
interface Branch { id: string; code: string; name: string }
interface Role { id: string; code: string }

/** A South-branch manager + student created through the API (setup for the cross-branch checks). */
async function southStudent() {
  const admin = await apiLogin('demo', 'demo.admin', PASSWORDS.demoAdmin);
  const branches = await api<Paged<Branch>>(admin.accessToken, 'GET', '/branches');
  const south = branches.body.items.find((b) => b.code === 'SOUTH')!;
  const roles = await api<Role[]>(admin.accessToken, 'GET', '/roles');
  const manager = roles.body.find((r) => r.code === 'BranchManager')!;
  const userName = `south.${unique()}`;
  const created = await api<{ id: string }>(admin.accessToken, 'POST', '/users', {
    userName, displayName: 'South Manager', email: null, phone: null, password: 'SouthMgr123', locale: null, timeZone: null,
  });
  expect(created.status).toBeLessThan(300);
  const assigned = await api(admin.accessToken, 'PUT', `/users/${created.body.id}/assignments`, [{ roleId: manager.id, branchId: south.id }]);
  expect(assigned.status).toBeLessThan(300);
  const southMgr = await apiLogin('demo', userName, 'SouthMgr123');
  const student = await api<{ id: string }>(southMgr.accessToken, 'POST', '/students', {
    branchId: south.id, firstName: 'Southern', lastName: `Student${unique()}`, status: 'active',
  });
  expect(student.status).toBeLessThan(300);
  return { southId: student.body.id };
}

test('branch.manager: guardian + student CRUD with a guardian link; edit keeps the portal account link', async ({ page }) => {
  await signInBranchManager(page);
  const suffix = unique();

  // Guardian
  await page.goto(`${ADMIN}/en/people/guardians/new`);
  await page.getByRole('combobox', { name: 'Branch' }).selectOption({ label: 'North Branch' });
  await textbox(page, 'First name').fill('Maryam');
  await textbox(page, 'Last name').fill(`Guardian${suffix}`);
  await textbox(page, 'Mobile number').fill('+98 912 111 2233');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Created successfully.' })).toBeVisible();

  // Student (number generated by the server)
  await page.goto(`${ADMIN}/en/people/students/new`);
  await page.getByRole('combobox', { name: 'Branch' }).selectOption({ label: 'North Branch' });
  await textbox(page, 'First name').fill('Kian');
  await textbox(page, 'Last name').fill(`Student${suffix}`);
  await page.getByLabel('Date of birth', { exact: false }).fill('2013-09-23');
  await page.getByRole('combobox', { name: 'Gender' }).selectOption('male');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Created successfully.' })).toBeVisible();
  await expect(textbox(page, 'Student number')).not.toHaveValue('');

  // Link the guardian
  await page.getByRole('button', { name: 'Add guardian' }).click();
  await page.getByRole('combobox', { name: 'Guardian' }).selectOption({ label: `Maryam Guardian${suffix}` });
  await page.getByRole('combobox', { name: 'Relationship' }).selectOption('mother');
  await page.getByRole('button', { name: 'Save guardians' }).click();
  await expect(page.getByText('Guardians saved.')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('combobox', { name: 'Guardian' })).toHaveValue(/.+/);
  await expect(page.getByRole('combobox', { name: 'Relationship' })).toHaveValue('mother');

  // Delete the student
  await page.getByRole('button', { name: 'Delete' }).first().click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete' }).click();
  await expect(page).toHaveURL(/\/en\/people\/students(\?notice=deleted)?$/);
});

test('editing a portal-linked student keeps its user link (student.one can still see the profile)', async ({ page }) => {
  await signInBranchManager(page);
  const bm = await apiLogin('demo', 'branch.manager', PASSWORDS.demoUser);
  const list = await api<Paged<{ id: string; studentNumber: string; userId: string | null }>>(bm.accessToken, 'GET', '/students?search=S0001');
  const sara = list.body.items.find((s) => s.studentNumber === 'S0001')!;
  expect(sara.userId).not.toBeNull();
  await page.goto(`${ADMIN}/en/people/students/${sara.id}`);
  await textbox(page, 'Mobile number').fill('+98 912 555 0101');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Changes saved.' })).toBeVisible();
  const after = await api<{ userId: string | null }>(bm.accessToken, 'GET', `/students/${sara.id}`);
  expect(after.body.userId).toBe(sara.userId);
});

test('stale rowVersion shows the translated concurrency conflict and can reload', async ({ page, browser }) => {
  await signInBranchManager(page);
  const bm = await apiLogin('demo', 'branch.manager', PASSWORDS.demoUser);
  const list = await api<Paged<{ id: string; studentNumber: string }>>(bm.accessToken, 'GET', '/students?search=S0002');
  const ali = list.body.items.find((s) => s.studentNumber === 'S0002')!;

  const second = await browser.newPage();
  await signInBranchManager(second);
  await page.goto(`${ADMIN}/en/people/students/${ali.id}`);
  await second.goto(`${ADMIN}/en/people/students/${ali.id}`);
  await expect(textbox(second, 'First name')).toHaveValue('Ali');

  await textbox(page, 'Last name').fill(`Karimi-${unique()}`);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Changes saved.' })).toBeVisible();

  await textbox(second, 'First name').fill('Alireza');
  await second.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(second.getByText('Someone else changed this record').first()).toBeVisible();
  await second.getByRole('button', { name: 'Load latest version' }).click();
  await expect(textbox(second, 'First name')).toHaveValue('Ali');
  await second.close();
});

test('cross-branch access is denied (no existence leak) and people screens need people permissions', async ({ page }) => {
  const { southId } = await southStudent();
  const bm = await apiLogin('demo', 'branch.manager', PASSWORDS.demoUser);
  expect((await api(bm.accessToken, 'GET', `/students/${southId}`)).status).toBe(404);
  const branches = await api<Paged<Branch>>(bm.accessToken, 'GET', '/branches');
  expect(branches.body.items.map((b) => b.code)).toEqual(['NORTH']);

  await signInBranchManager(page);
  await page.goto(`${ADMIN}/en/people/students/${southId}`);
  await expect(alertBox(page)).toContainText('wasn’t found');
  await page.goto(`${ADMIN}/en/people/students`);
  await expect(page.getByText('Southern')).toHaveCount(0);

  // A tenant admin without people permissions gets the forbidden state, not a crash.
  // Leave the app first: a request still in flight would hit 401 after the cookies go and redirect to login,
  // aborting the next navigation (seen as a flaky net::ERR_ABORTED in the M2 run).
  await page.goto('about:blank');
  await page.context().clearCookies();
  await signInDemoAdmin(page);
  await page.goto(`${ADMIN}/en/people/students`);
  await expect(page.getByText('You don’t have access to this page').or(page.getByText('You do not have permission')).first()).toBeVisible();
});
